def organization_label(value):
    text = str(value or "")
    key = re.sub(r"\s+", " ", text.strip()).casefold()
    return LABELS.get(key, text)


def localize_position(row):
    return {**row, "display_title": organization_label(row.get("title")),
            "department_display_name": organization_label(row.get("department"))}
